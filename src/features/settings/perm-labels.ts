/** Human label for a permission key; unknown keys get one built from the key. */
export function permLabel(perm: string): string {
  const known = PERM_LABELS[perm as Perm];
  if (known) return known;
  const [mod = "", ...rest] = perm.split(".");
  const action = rest.join(" ").replace(/_/g, " ").trim();
  const words = action ? `${action} ${mod.replace(/_/g, " ")}` : mod;
  return words.charAt(0).toUpperCase() + words.slice(1);
}

export function permDescription(perm: string): string {
  return PERM_DESCRIPTIONS[perm as Perm] ?? "";
}
