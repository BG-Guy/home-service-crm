import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { PrintButton } from "@/features/tools/components/PrintButton";
import { listTools } from "@/features/tools/queries";
import { qrPayload } from "@/features/tools/rules";
import { requireUser } from "@/lib/auth/current";
import { appUrl } from "@/lib/env";
import { qrSvg } from "@/lib/qr";
import { isEnabled } from "@/lib/settings";
import { Page } from "@/ui/components/AppShell";
import { EmptyState } from "@/ui/components/EmptyState";
import { NavBar } from "@/ui/components/NavBar";

export const metadata: Metadata = { title: "Tool labels" };

/**
 * Printable QR label sheet (SPEC M18). The QR is an inline SVG made on the server by
 * the tiny hand-rolled encoder (no library ships to the browser). Each code opens
 * /tools/[id]; the check-out sheet scans them with BarcodeDetector.
 */
export default async function ToolLabelsPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  await requireUser("tools.manage");
  if (!(await isEnabled("tools"))) notFound();
  const sp = await searchParams;
  const ids = typeof sp.ids === "string" ? new Set(sp.ids.split(",")) : null;
  const origin = appUrl("");
  const list = (await listTools({ scope: "all", status: "all" })).filter(
    (t) =>
      t.owner === "company" &&
      t.status !== "retired" &&
      (!ids || ids.has(t.id)),
  );
  return (
    <>
      <div className="print:hidden">
        <NavBar
          title="QR labels"
          back={{ href: "/tools", label: "Tools" }}
          trailing={<PrintButton label="Print labels" />}
        />
      </div>
      <Page wide className="pt-4 print:p-0">
        {list.length === 0 ? (
          <div className="list-card">
            <EmptyState
              title="No tools to label"
              message="Add company tools first."
            />
          </div>
        ) : (
          <>
            <p className="pb-3 text-footnote text-label-2 print:hidden">
              {list.length} labels · prints on letter paper (3 across). Stick
              one on each tool where it stays visible.
            </p>
            <ul className="grid grid-cols-2 gap-3 sm:grid-cols-3 print:grid-cols-3 print:gap-2">
              {list.map((t) => (
                <li
                  key={t.id}
                  className="flex break-inside-avoid items-center gap-3 rounded-[10px] border border-[var(--sep)] bg-white p-3 text-black"
                >
                  <span
                    className="block size-20 shrink-0 [&>svg]:size-full"
                    // biome-ignore lint/security/noDangerouslySetInnerHtml: SVG generated by our own encoder from a URL we built
                    dangerouslySetInnerHTML={{
                      __html: qrSvg(qrPayload(origin, t.id), {
                        ecl: "M",
                        title: t.name,
                      }),
                    }}
                  />
                  <span className="min-w-0">
                    <span className="block truncate text-[13px] font-semibold">
                      {t.name}
                    </span>
                    <span className="block text-[12px] font-mono">
                      {t.assetTag}
                    </span>
                    {t.serial && (
                      <span className="block truncate text-[11px]">
                        S/N {t.serial}
                      </span>
                    )}
                  </span>
                </li>
              ))}
            </ul>
          </>
        )}
      </Page>
    </>
  );
}
