// Motion tokens — docs/DESIGN.md §3 "Motion tokens" (was SPEC §12.2). Apple WWDC23
// spring conversion (mass 1):
//   duration d (s) + bounce b  →  stiffness (2π/d)², damping (1−b)·4π/d.
// A CSS animation of a spring lasts SETTLE × d (≥ 99.5 % settled), so each `--dur-*`
// token maps to the spring `forDuration(ms, bounce)`. The `linear()` curves below
// come from `springLinear()` (./easing.ts), which samples the JS driver's solution.
// Isomorphic (no DOM access at import time).

export interface IosSpring {
  type: "spring";
  mass: number;
  stiffness: number;
  damping: number;
}

export const ios = (d: number, b = 0): IosSpring => ({
  type: "spring" as const,
  mass: 1,
  stiffness: ((2 * Math.PI) / d) ** 2,
  damping: ((1 - b) * 4 * Math.PI) / d,
});

/** CSS animation length ÷ the spring's Apple duration (where it is ≥ 99.5 % settled). */
export const SETTLE = 1.2;

/** Durations in ms (mirror `--dur-*` in globals.css). */
export const DUR = {
  press: 120, // press-in
  quick: 220, // release, chips, toggles, tab indicator, badge
  snappy: 320, // sheets, popovers, menus, toasts out
  push: 400, // page push / pop, shared-element morph
  bouncy: 480, // success check, toast in, rating star
} as const;

/** The spring whose CSS animation lasts `ms` (Apple duration `ms / SETTLE`). */
export const forDuration = (ms: number, bounce = 0): IosSpring =>
  ios(ms / 1000 / SETTLE, bounce);

/** Named springs. Pass to Motion (`transition={spring.snappy}`) or to `springTo()`. */
