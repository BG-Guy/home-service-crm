export type IconName = keyof typeof icons;

/** Resolve a manifest icon name; unknown names fall back to a neutral dot icon. */
export function iconFor(name: string | null | undefined): IconComponent {
  return (name && (icons as Record<string, IconComponent>)[name]) || Ellipsis;
}
